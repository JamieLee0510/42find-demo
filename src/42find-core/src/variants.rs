//! 变体表：**规范形 → 变体集**。
//!
//! ⚠️ 存的**不是**成对等价。等价关系天然对称且传递——写下 `发≡發` 与 `发≡髮`，
//! 就隐含了 `發≡髮`，于是查「發」会命中「髮」，我们靠查询扩展避开的假阳性从后门溜回来。
//! 实际语感是**非对称**的：简体「发」本就同时对应「發」与「髮」，
//! 但繁体用户查「發」绝不期待命中「髮」。所以变体只回连规范形，**不连兄弟变体**。
//!
//! 手写小表，只覆盖黄金查询集用得到的字（`vault/truth/queries.tsv`）。
//! 表外字符原样匹配——不报错，也不静默丢弃。

/// 规范形（简体）→ 该规范形的全部变体，不含规范形自身。
pub(crate) const VARIANTS: &[(char, &[char])] = &[
    ('检', &['檢']),
    ('归', &['歸']),
    ('变', &['變']),
    ('体', &['體']),
    ('发', &['發', '髮']), // 一对多：简体一个字对应两个繁体
    ('户', &['戶']),
];

/// `c` 是某个规范形？是则返回它的变体集。
pub(crate) fn variants_of(c: char) -> Option<&'static [char]> {
    VARIANTS.iter().find(|(k, _)| *k == c).map(|(_, v)| *v)
}

/// `c` 是某个变体？是则返回它的规范形。
pub(crate) fn canonical_of(c: char) -> Option<char> {
    VARIANTS
        .iter()
        .find(|(_, vs)| vs.contains(&c))
        .map(|(k, _)| *k)
}
